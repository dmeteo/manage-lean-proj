import { expect, test } from '@playwright/test'
import { account } from '../src/mocks/fixtures'

test('руководитель входит, видит просрочку и завершает сеанс', async ({ page }) => {
  await page.goto('/dashboard')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('Логин').fill(account.login)
  await page.getByLabel('Пароль').fill('incorrect')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Неверный логин или пароль')

  await page.getByLabel('Пароль').fill(account.password)
  await page.getByLabel('Пароль').press('Enter')
  await expect(page.getByRole('heading', { name: 'Дашборд' })).toBeVisible()
  const overdue = page.getByRole('row').filter({ hasText: 'Провести замер времени переналадки' })
  await expect(overdue).toContainText('Сокращение времени переналадки')
  await expect(overdue).toContainText('25.11.2026')
  await expect(overdue).toContainText('Просрочено')

  await page.reload()
  await expect(overdue).toBeVisible()
  await page.getByRole('region', { name: 'Нагрузка по срокам' }).getByRole('link', { name: /Просрочено/ }).click()
  await expect(page).toHaveURL(/\/activities\?overdue=1$/)
  await expect(overdue).toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: 'Проверить карту текущего потока' })).toHaveCount(0)
  await page.getByRole('navigation').getByRole('link', { name: 'Проекты' }).click()
  await expect(page.getByRole('link', { name: 'Снижение ожидания материалов' })).toBeVisible()
  const search = page.getByRole('searchbox', { name: 'Поиск по названию проекта' })
  await search.fill('переналадки')
  await search.press('Enter')
  await expect(page).toHaveURL(/\/projects\?search=/)
  const project = page.getByRole('link', { name: 'Сокращение времени переналадки' })
  await expect(project).toBeVisible()
  await expect(page.getByRole('link', { name: 'Снижение ожидания материалов' })).toHaveCount(0)
  await project.click()
  await expect(page.getByRole('heading', { name: 'План проекта' })).toBeVisible()
  const completed = page.getByRole('row').filter({ hasText: 'Определить границы пилотного участка' })
  await expect(completed).toContainText('20.11.2026')
  await expect(completed).toContainText('19.11.2026')
  await completed.getByRole('link').click()
  await expect(page.getByRole('region', { name: 'История проверки' })).toContainText('Границы участка подтверждены')
  await page.getByRole('link', { name: 'К плану проекта' }).click()
  await page.getByRole('link', { name: 'Проверить карту текущего потока' }).click()
  await expect(page.getByRole('region', { name: 'Документы' })).toContainText('Карта текущего потока.pdf')
  await page.getByRole('button', { name: 'Выйти' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.goto('/projects')
  await expect(page).toHaveURL(/\/login$/)
})
